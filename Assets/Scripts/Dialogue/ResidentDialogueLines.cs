    static Dictionary<string, List<Entry>> _byTopic;

    public static IReadOnlyList<Entry> For(string topic)
    {
        if (_byTopic == null)
        {
            _byTopic = new Dictionary<string, List<Entry>>();
            foreach (var entry in All)
            {
                if (!_byTopic.TryGetValue(entry.Topic, out var list)) _byTopic[entry.Topic] = list = new List<Entry>();
                list.Add(entry);
            }
        }
        return _byTopic.TryGetValue(topic, out var found) ? found : (IReadOnlyList<Entry>)System.Array.Empty<Entry>();
    }
